def _bundle_archive(directory, snapshot, image):
    """Return (filename, bytes) for the handover package of *directory*.

    A flat zip: the build context that was just written into the
    directory, the notebooks and dependency files it describes, a README
    for whoever has to build it, and a compose file that does the build
    and the run in one command. Flat because the tester unpacks it and
    builds in the
    unpacked directory — a directory prefix would only be one more
    thing to get wrong.

    The build-context files are read back from disk rather than
    generated a second time, so the package and the directory cannot
    disagree about what was frozen. *image* is only a fallback for the
    README: the manifest on disk is the authority.
    """
    tag = _generated_tag(directory)

    context = []
    manifest_data = None
    for name in (DOCKERFILE_NAME, DOCKERIGNORE_NAME, MANIFEST_NAME):
        data = _bundle_member_bytes(directory / name)
        if data is None:
            continue
        if name == MANIFEST_NAME:
            manifest_data = data
        context.append((name, data))

    notebooks = _bundle_files(directory, snapshot["notebooks"])
    requirements = _bundle_files(directory, snapshot["requirements"])

    manifest = _bundle_manifest(manifest_data)
    if not manifest.get("image"):
        # Only reached when the manifest could not be read back; the
        # file on disk is otherwise the authority on what this is.
        manifest["image"] = image
    readme = _generate_bundle_readme(
        directory,
        tag,
        manifest,
        [name for name, _ in notebooks],
        [name for name, _ in requirements],
        snapshot["missing"],
    )
    compose = _generate_compose(tag)

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in context + notebooks + requirements:
            archive.writestr(name, data)
        archive.writestr(BUNDLE_README_NAME, readme)
        archive.writestr(BUNDLE_COMPOSE_NAME, compose)

    filename = f"{_directory_slug(directory)}_frozen_{_utc_stamp()}.zip"
    return filename, buffer.getvalue()


def _write_bundle(directory, name, data):
    """Write the handover package into *directory*; return True on success.

    The download is the primary path, so a directory that cannot be
    written to costs the copy and nothing else: the caller still has the
    bytes and says in a response header whether the copy landed.
    """
    try:
        (directory / name).write_bytes(data)
    except OSError as e:
        log.warning("Freeze: cannot write %s: %s", name, e)
        return False

    return True


def _freeze_snapshot(handler, path):
    """Return the freeze snapshot for *path*.

    The keys are "directory", "requirements", "notebooks", "conflicts",
    "notebook_installs", "environment", "user_installed", "missing",
    "python_version" and "provenance_method". It is a mapping rather
    than a tuple because "environment" and "user_installed" are both
    lists of package records, and positional unpacking is one edit away
    from silently swapping them.

    Both freeze endpoints collect the snapshot this way, so they answer
    the same 400 and 404, never differ on what a directory contains, and
    scan the live environment exactly once per request.
    """
    root = _server_root_dir(handler.settings)

    directory = _resolve_within_root(root, path)
    if directory is None:
        log.warning("Freeze: rejected path outside the root: %r", path)
        raise web.HTTPError(
            400, "Requested path is outside the server root directory"
        )
    if not directory.is_dir():
        log.warning("Freeze: directory not found: %r", path)
        raise web.HTTPError(404, "Directory not found")

    requirements = _collect_requirements(directory, root)
    notebooks = _collect_notebooks(directory, root)
    conflicts = _find_conflicts(notebooks, requirements)
    installs = _notebook_installs(notebooks)

    scan = _scan_environment()
    environment, missing = _resolve_environment(notebooks, scan)

    return {
        "directory": directory,
        "requirements": requirements,
        "notebooks": notebooks,
        "conflicts": conflicts,
        "notebook_installs": installs,
        "environment": environment,
        "user_installed": _user_installed(scan),
        "missing": missing,
        "python_version": scan["python_version"],
        "provenance_method": scan["provenance_method"],
    }


class TrackHandler(APIHandler):
    @web.authenticated
    async def post(self):
        body = json.loads(self.request.body)
        notebook = body.get("notebook", "")
        username = body.get("username", "")
        url = body.get("url", "") or "https://ganymede.icos-cp.eu"

        params = urllib.parse.urlencode({
            "idsite": MATOMO_SITE_ID,
            "rec": "1",
            "action_name": f"{username}:{notebook}",
            "url": url,
            "uid": f"{username}:{notebook}",
            "ua": self.request.headers.get("User-Agent", ""),
        })

        try:
            client = AsyncHTTPClient()
            await client.fetch(f"{MATOMO_URL}?{params}", raise_error=False)
        except Exception as e:
            log.warning("Matomo tracking failed: %s", e)

        self.finish(json.dumps({"status": "ok"}))


class FreezeHandler(APIHandler):
    """Snapshot of the session image plus a directory's dependency files."""

    @web.authenticated
    def get(self):
        path = self.get_query_argument("path", default="")
        snapshot = _freeze_snapshot(self, path)

        image = _session_image()
        blocked = _dockerfile_block_reason(
            image, snapshot["conflicts"], snapshot["notebook_installs"]
        )
        dockerfile = None
        written = None
        dockerignore_written = None
        manifest_written = None
        if blocked is None:
            dockerfile = _generate_dockerfile(
                path,
                image,
                snapshot["environment"],
                snapshot["user_installed"],
                snapshot["missing"],
                snapshot["python_version"],
                snapshot["provenance_method"],
            )
            # A GET that writes to disk is not ideal, but freezing has to
            # leave the build context next to the notebooks without a
            # second click. The writes are idempotent: content that
            # already matches is left untouched, and a hand-written
            # Dockerfile or .dockerignore is never replaced.
            context = _write_build_context(
                snapshot["directory"], dockerfile, image, snapshot
            )
            written = context["dockerfile"]
            dockerignore_written = context["dockerignore"]
            manifest_written = context["manifest"]

        self.finish(json.dumps({
            "path": path,
            "image": image,
            "python_version": snapshot["python_version"],
            "provenance_method": snapshot["provenance_method"],
            # Names only. The content of each dependency file is
            # collected for the conflict check and stays on the
            # server; nothing in the browser reads it.
            "requirements": [
                item["name"] for item in snapshot["requirements"]
            ],
            "notebooks": snapshot["notebooks"],
            "environment": snapshot["environment"],
            "user_installed": snapshot["user_installed"],
            "missing": snapshot["missing"],
            "conflicts": snapshot["conflicts"],
            "notebook_installs": snapshot["notebook_installs"],
            "dockerfile": dockerfile,
            "dockerfile_blocked": blocked,
            "dockerfile_written": written,
            "dockerignore_written": dockerignore_written,
            "manifest_written": manifest_written,
            # Whether the frontend may offer the handover package.
            # True only when a generated Dockerfile is actually on
            # disk: the package is built around that file, and a
            # Dockerfile that was generated but never written is no
            # use to whoever has to build it. The bundle endpoint
            # refuses on the same two checks.
            "bundle_available": written in DOCKERFILE_ON_DISK,
        }))


class BundleHandler(APIHandler):
    """Serves a frozen directory as a zip someone else can build and run.

    The freeze leaves a build context beside the notebooks, which is
    enough for whoever is already sitting in front of that directory. A
    tester is not: they get this package and nothing else, so it carries
    the notebooks, their dependency files, the build context and a
    README with the real commands in it.

    A copy is left in the frozen directory as well, so the same package
    can be handed on again later without freezing a second time.
    """

    def finish(self, *args, **kwargs):
        """Finish the response, keeping the Content-Type set in get().

        APIHandler.finish sets "Content-Type: application/json" on every
        response it completes. Newer jupyter_server versions take a
        "set_content_type" keyword to say otherwise and older 2.x ones
        do not, so that one line is skipped rather than argued with, and
        each response below sets its own content type.
        """
        self.update_api_activity()
        return super(APIHandler, self).finish(*args, **kwargs)

    @web.authenticated
    def get(self):
        path = self.get_query_argument("path", default="")

        # The snapshot is collected from the directory itself, so the
        # package is refused for the same reasons a freeze would be.
        snapshot = _freeze_snapshot(self, path)
        directory = snapshot["directory"]

        image = _session_image()
        blocked = _dockerfile_block_reason(
            image, snapshot["conflicts"], snapshot["notebook_installs"]
        )
        if blocked is not None:
            self.set_status(409)
            self.set_header("Content-Type", "application/json")
            self.finish(json.dumps({"status": "blocked", "reason": blocked}))
            return

        dockerfile = _generate_dockerfile(
            path,
            image,
            snapshot["environment"],
            snapshot["user_installed"],
            snapshot["missing"],
            snapshot["python_version"],
            snapshot["provenance_method"],
        )
        # The context is written before the archive is built, and the
        # archive then reads it back, so what the tester unpacks is what
        # the frozen directory holds.
        context = _write_build_context(
            directory, dockerfile, image, snapshot
        )
        if context["dockerfile"] not in DOCKERFILE_ON_DISK:
            # Without a generated Dockerfile on disk the package
            # would carry someone else's Dockerfile, or none at all,
            # while its README tells the tester to build from it.
            self.set_status(409)
            self.set_header("Content-Type", "application/json")
            self.finish(json.dumps({
                "status": "blocked",
                "reason": _dockerfile_write_reason(
                    context["dockerfile"]
                ),
            }))
            return

        name, data = _bundle_archive(directory, snapshot, image)
        saved = _write_bundle(directory, name, data)

        self.set_header("Content-Type", "application/zip")
        self.set_header("Content-Disposition", f'attachment; filename="{name}"')
        if saved:
            # Only set when the copy landed, so the frontend can say
            # "downloaded" rather than "saved beside your notebooks"
            # without having to guess.
            self.set_header("X-Icos-Freeze-Saved", name)
        self.finish(data)


def setup_handlers(web_app):
    base_url = web_app.settings.get("base_url", "/")
    handlers = [
        (url_path_join(base_url, "icos-ext", "track"), TrackHandler),
        (url_path_join(base_url, "icos-ext", "freeze"), FreezeHandler),
        (url_path_join(base_url, "icos-ext", "bundle"), BundleHandler),
    ]
    web_app.add_handlers(".*$", handlers)
